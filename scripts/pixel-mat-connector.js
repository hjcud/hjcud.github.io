(() => {
  const design = document.querySelector('#pixel-mat .pm-design');
  const connector = design?.querySelector('.pm-process-connector');
  const comparison = design?.querySelector('.pm-comparison');
  const target = design?.querySelector('.pm-listed-step .pm-board-img');
  if (!connector || !comparison || !target) return;
  let frame = 0;
  const draw = () => {
    frame = 0;
    const box = design.getBoundingClientRect();
    const from = comparison.getBoundingClientRect();
    const to = target.getBoundingClientRect();
    if (!box.width || !from.height || !to.height) return;
    const sx = 24;
    const sy = from.bottom - box.top;
    const tx = to.left - box.left - (box.width < 600 ? 6 : 12);
    const ty = to.top - box.top + to.height * .5;
    const minX = 8 - box.left;
    const outer = -Math.min(24, Math.max(6, box.left - 10));
    const tail = Math.max(minX, tx - 24);
    const path = `M${sx} ${sy} C${sx - 34} ${sy + 10} ${outer} ${sy + 14} ${outer} ${sy + 54} C${outer} ${ty - 28} ${tail} ${ty} ${tx} ${ty}`;
    const wing = Math.min(8, tx - minX);
    connector.setAttribute('viewBox', `0 0 ${box.width} ${ty + 14}`);
    connector.style.height = `${ty + 14}px`;
    connector.querySelector('.pm-connector-line').setAttribute('d', path);
    connector.querySelector('.pm-connector-head').setAttribute('d', `M${tx - wing} ${ty - 5} L${tx} ${ty} L${tx - wing} ${ty + 5}`);
    const origin = connector.querySelector('.pm-connector-origin');
    origin.setAttribute('cx', sx);
    origin.setAttribute('cy', sy);
  };
  const schedule = () => { if (!frame) frame = requestAnimationFrame(draw); };
  const observer = new ResizeObserver(schedule);
  [design, comparison, target].forEach(element => observer.observe(element));
  target.addEventListener('load', schedule);
  document.fonts.ready.then(schedule);
  schedule();
})();
